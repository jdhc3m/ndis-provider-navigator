"""Read and write ``evals/extraction_labels.yaml``, the hand-checked extraction labels.

The file is the same small, fixed YAML subset the entity-resolution sample uses: a comment
header, ``seed`` and ``sites``, one block mapping per site whose string values are
JSON-quoted and whose ``services`` list is a JSON array. ``key`` is a hash of the Maps
place id (never the id itself); ``provider_key`` is the ABN when the place is linked to
the register and the place id otherwise, matching the page cache. Only ``services`` and
``labelled_by`` are meant to be edited, and only for sites whose pages a person has read.
"""

import json
from collections.abc import Iterable
from dataclasses import dataclass

from ndis.domain.taxonomy import Service, service_of

LABELLED_BY_AGENT = "agent"
LABELLED_BY_VALUES = (LABELLED_BY_AGENT,)

HEADER = """\
# Extraction hand-check labels. Generated by scripts/make_extraction_labels.py; edit only
# `services` and `labelled_by`, and only for sites whose stored pages (data/private/pages,
# listed in page_meta in data/ndis.db) you have read in full. `key` is a hash of the Maps
# place id; `provider_key` is the ABN when the place is linked to the register, else the
# place id — it is the key of the extraction cache. `services` lists the taxonomy keys
# (src/ndis/domain/taxonomy.py) the provider truly offers, judged only from its pages.
# `labelled_by` is null until labelled; the builder sets it to "agent".
"""

FIELDS = ("key", "maps_title", "provider_key", "services", "labelled_by")


class LabelFormatError(ValueError):
    """The labels file does not follow the layout this module writes."""


@dataclass(frozen=True)
class LabelSite:
    """One labelled (or template) site: identity plus the true service set."""

    key: str
    maps_title: str
    provider_key: str
    services: tuple[Service, ...]
    labelled_by: str | None


def _scalar(value: object) -> str:
    if value is None:
        return "null"
    if isinstance(value, tuple):
        return json.dumps([getattr(item, "value", item) for item in value], ensure_ascii=False)
    return json.dumps(str(value), ensure_ascii=False)


def write_labels(path, sites: Iterable[LabelSite], seed: int) -> None:  # type: ignore[no-untyped-def]
    """Write the header, ``seed`` and one block mapping per site."""
    lines = [HEADER, f"seed: {seed}", "sites:"]
    for site in sites:
        values = [
            ("key", site.key),
            ("maps_title", site.maps_title),
            ("provider_key", site.provider_key),
            ("services", site.services),
            ("labelled_by", site.labelled_by),
        ]
        first, rest = values[0], values[1:]
        lines.append(f"- {first[0]}: {_scalar(first[1])}")
        lines.extend(f"  {field}: {_scalar(value)}" for field, value in rest)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def _parse_scalar(text: str) -> object:
    text = text.strip()
    if text in ("null", "~", ""):
        return None
    try:
        return json.loads(text)
    except json.JSONDecodeError:
        return text


def read_labels(path) -> tuple[LabelSite, ...]:  # type: ignore[no-untyped-def]
    """Parse the file back; raises ``LabelFormatError`` on unknown fields or services."""
    rows: list[dict[str, object]] = []
    current: dict[str, object] | None = None
    for number, raw in enumerate(path.read_text(encoding="utf-8").splitlines(), start=1):
        line = raw.rstrip()
        if not line or line.lstrip().startswith("#") or line.startswith(("sites:", "seed:")):
            continue
        if line.startswith("- "):
            current = {}
            rows.append(current)
            line = "  " + line[2:]
        if current is None or not line.startswith("  ") or ":" not in line:
            raise LabelFormatError(f"{path}:{number}: unexpected line {raw!r}")
        field, _, value = line.strip().partition(":")
        if field not in FIELDS:
            raise LabelFormatError(f"{path}:{number}: unknown field {field!r}")
        current[field] = _parse_scalar(value)
    parsed: list[LabelSite] = []
    for row in rows:
        missing = [field for field in FIELDS if field not in row]
        if missing:
            raise LabelFormatError(f"{path}: row {row.get('key')!r} is missing {missing}")
        services: list[Service] = []
        for key in row["services"] if isinstance(row["services"], list) else []:
            service = service_of(str(key))
            if service is None:
                raise LabelFormatError(f"{path}: row {row['key']!r} names unknown service {key!r}")
            services.append(service)
        labelled_by = row["labelled_by"]
        if labelled_by is not None and labelled_by not in LABELLED_BY_VALUES:
            raise LabelFormatError(
                f"{path}: row {row['key']!r} has labelled_by {labelled_by!r}; "
                f"allowed: {LABELLED_BY_VALUES}"
            )
        parsed.append(
            LabelSite(
                key=str(row["key"]),
                maps_title=str(row["maps_title"]),
                provider_key=str(row["provider_key"]),
                services=tuple(services),
                labelled_by=None if labelled_by is None else str(labelled_by),
            )
        )
    return tuple(parsed)


def labelled(sites: Iterable[LabelSite]) -> tuple[LabelSite, ...]:
    """The sites a person has labelled, in file order."""
    return tuple(site for site in sites if site.labelled_by is not None)


def merge_labels(rows: Iterable[LabelSite], previous: Iterable[LabelSite]) -> tuple[LabelSite, ...]:
    """Carry a previous label over to the regenerated row with the same key."""
    kept = {site.key: site for site in previous}
    return tuple(
        kept[site.key] if site.key in kept and kept[site.key].labelled_by is not None else site
        for site in rows
    )
