"""Read and write ``evals/er_sample.yaml``, the hand-checked entity-resolution sample.

The file is a small, fixed YAML subset written and parsed here without a YAML library: a
comment header, ``seed`` and ``rows``, and one block mapping per row whose string values are
JSON-quoted (valid YAML flow scalars) and whose ``candidates`` list is a JSON array (a valid
YAML flow sequence). Only public-safe fields appear: the Maps title, the matched register
name and ABN, the register candidates of an ambiguous row, and the matcher's status,
strategy and confidence. Rows are keyed by a hash of the place id so the id itself is never
committed.
"""

import hashlib
import json
from collections.abc import Iterable
from dataclasses import dataclass, replace
from pathlib import Path

from ndis.domain.entity_resolution import ProviderLink
from ndis.domain.evaluation import VERDICTS

HEADER = """\
# Entity-resolution hand-check sample. Generated by scripts/resolve_entities.py; do not edit
# anything except `verdict`. Allowed verdicts: correct, incorrect, unsure (leave null until
# checked). `key` is a hash of the Maps place id so existing verdicts survive a regeneration.
# `candidates` lists the register providers ("ABN name") an ambiguous row could be, so it can
# be judged without re-running. Precision (evals/test_entity_resolution.py) counts only
# correct/incorrect rows.
"""

FIELDS = (
    "key",
    "maps_title",
    "match_status",
    "strategy",
    "confidence",
    "abn",
    "register_name",
    "candidates",
    "verdict",
)
# Added after the first sample was written; an older file without it still reads.
OPTIONAL_FIELDS = frozenset({"candidates"})


class SampleFormatError(ValueError):
    """The sample file does not follow the layout this module writes."""


@dataclass(frozen=True)
class SampleRow:
    """One line of the hand-check sample; ``verdict`` is the only field a person fills."""

    key: str
    maps_title: str
    match_status: str
    strategy: str
    confidence: float
    abn: str | None
    register_name: str | None
    candidates: tuple[str, ...]
    verdict: str | None


def place_key(place_id: str) -> str:
    """Stable public-safe key for a place: the first 12 hex digits of its SHA-256."""
    return hashlib.sha256(place_id.encode("utf-8")).hexdigest()[:12]


def sample_row(link: ProviderLink, verdict: str | None = None) -> SampleRow:
    """The public-safe projection of a link; candidates are rendered as ``"ABN name"``."""
    return SampleRow(
        key=place_key(link.place.place_id),
        maps_title=link.place.title,
        match_status=link.match.match_status.value,
        strategy=link.match.strategy.value,
        confidence=link.match.confidence,
        abn=link.match.abn,
        register_name=link.match.matched_name,
        candidates=tuple(f"{c.abn} {c.name}" for c in link.match.candidates),
        verdict=verdict,
    )


def _scalar(value: object) -> str:
    if value is None:
        return "null"
    if isinstance(value, bool | int | float):
        return json.dumps(value)
    if isinstance(value, tuple):
        return json.dumps(list(value), ensure_ascii=False)
    return json.dumps(str(value), ensure_ascii=False)


def write_sample(path: Path, rows: Iterable[SampleRow], seed: int) -> None:
    """Write the header, ``seed`` and one block mapping per row, creating parent folders."""
    lines = [HEADER, f"seed: {seed}", "rows:"]
    for row in rows:
        values = [(field, getattr(row, field)) for field in FIELDS]
        first, rest = values[0], values[1:]
        lines.append(f"- {first[0]}: {_scalar(first[1])}")
        lines.extend(f"  {field}: {_scalar(value)}" for field, value in rest)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def _parse_scalar(text: str) -> object:
    text = text.strip()
    if text in ("null", "~", ""):
        return None
    try:
        return json.loads(text)
    except json.JSONDecodeError:
        return text


def read_sample(path: Path) -> tuple[SampleRow, ...]:
    """Parse the file back; raises ``SampleFormatError`` on an unknown field or verdict."""
    rows: list[dict[str, object]] = []
    current: dict[str, object] | None = None
    for number, raw in enumerate(path.read_text(encoding="utf-8").splitlines(), start=1):
        line = raw.rstrip()
        if not line or line.lstrip().startswith("#") or line.startswith(("rows:", "seed:")):
            continue
        if line.startswith("- "):
            current = {}
            rows.append(current)
            line = "  " + line[2:]
        if current is None or not line.startswith("  ") or ":" not in line:
            raise SampleFormatError(f"{path}:{number}: unexpected line {raw!r}")
        field, _, value = line.strip().partition(":")
        if field not in FIELDS:
            raise SampleFormatError(f"{path}:{number}: unknown field {field!r}")
        current[field] = _parse_scalar(value)
    parsed = []
    for row in rows:
        missing = [field for field in FIELDS if field not in row and field not in OPTIONAL_FIELDS]
        if missing:
            raise SampleFormatError(f"{path}: row {row.get('key')!r} is missing {missing}")
        verdict = row["verdict"]
        if verdict is not None and verdict not in VERDICTS:
            raise SampleFormatError(
                f"{path}: row {row['key']!r} has verdict {verdict!r}; allowed: {VERDICTS}"
            )
        candidates = row.get("candidates", [])
        if not isinstance(candidates, list):
            raise SampleFormatError(f"{path}: row {row['key']!r} candidates must be a list")
        parsed.append(
            SampleRow(
                key=str(row["key"]),
                maps_title=str(row["maps_title"]),
                match_status=str(row["match_status"]),
                strategy=str(row["strategy"]),
                confidence=float(row["confidence"]),  # type: ignore[arg-type]
                abn=None if row["abn"] is None else str(row["abn"]),
                register_name=None if row["register_name"] is None else str(row["register_name"]),
                candidates=tuple(str(candidate) for candidate in candidates),
                verdict=None if verdict is None else str(verdict),
            )
        )
    return tuple(parsed)


def merge_verdicts(
    rows: Iterable[SampleRow], previous: Iterable[SampleRow]
) -> tuple[SampleRow, ...]:
    """Carry a previously filled verdict over to the new row with the same key."""
    kept = {row.key: row.verdict for row in previous if row.verdict is not None}
    return tuple(replace(row, verdict=kept.get(row.key)) for row in rows)
